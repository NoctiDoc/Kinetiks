/**
 * Retourne les URLs des 2 photos séquentielles réelles free-exercise-db
 */
export function getExerciseMediaUrls(exercise) {
  if (!exercise || !exercise.freeExerciseDbSlug) {
    return { start: null, end: null };
  }
  const slug = encodeURIComponent(exercise.freeExerciseDbSlug);
  return {
    start: `${FREE_EXERCISE_DB_BASE}/${slug}/0.jpg`,
    end: `${FREE_EXERCISE_DB_BASE}/${slug}/1.jpg`,
  };
}

/**
 * Retourne les calques SVG médicaux open-source wger (vue antérieure & postérieure)
 * avec séparation moteurs primaires (accent vif) / stabilisateurs (accent atténué).
 */
export function getWgerAnatomyLayers(exercise) {
  const primary = Array.isArray(exercise?.wgerPrimaryIds) ? exercise.wgerPrimaryIds : [];
  const secondary = Array.isArray(exercise?.wgerSecondaryIds) ? exercise.wgerSecondaryIds : [];

  const splitByView = (ids, folder) => {
    const front = [];
    const back = [];
    for (const id of ids) {
      const meta = WGER_MUSCLES[id];
      if (!meta) continue;
      const url = `${WGER_BASE}/${folder}/muscle-${id}.svg`;
      if (meta.view === 'front') front.push({ id, name: meta.name, url });
      else back.push({ id, name: meta.name, url });
    }
    return { front, back };
  };

  const pLayers = splitByView(primary, 'main');
  const sLayers = splitByView(secondary, 'secondary');

  return {
    frontBase: `${WGER_BASE}/muscular_system_front.svg`,
    backBase: `${WGER_BASE}/muscular_system_back.svg`,
    frontPrimary: pLayers.front,
    frontSecondary: sLayers.front,
    backPrimary: pLayers.back,
    backSecondary: sLayers.back,
  };
}

